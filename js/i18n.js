function getLang() {
  const v = localStorage.getItem(LANG_KEY);
  return LANGS.some((l) => l.id === v) ? v : "cs";
}

function setLang(id) {
  localStorage.setItem(LANG_KEY, id);
  location.reload();
}

function t(key, vars) {
  const pack = I18N[getLang()] || I18N.cs;
  let s = pack[key] ?? I18N.cs[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.replaceAll("{" + k + "}", vars[k]);
    });
  }
  return s;
}

function applyI18n() {
  document.documentElement.lang = getLang();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (el.tagName === "META" || el.tagName === "TITLE") return;
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  const titleEl = document.querySelector("title[data-i18n]");
  if (titleEl) document.title = t(titleEl.dataset.i18n);
  document.querySelectorAll("meta[data-i18n]").forEach((el) => {
    el.content = t(el.dataset.i18n);
  });
}

function langSelectHtml() {
  const cur = getLang();
  return `<label class="lang-wrap"><span class="visually-hidden">${t("lang")}</span>
    <select class="lang-select" aria-label="${t("lang")}">
      ${LANGS.map((l) => `<option value="${l.id}" ${l.id === cur ? "selected" : ""}>${l.label}</option>`).join("")}
    </select></label>`;
}
